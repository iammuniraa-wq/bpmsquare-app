// Generates scripts/seed-estimator-products-demo.sql: the illustrative precast catalogue
// (products, services, a tool and BOM kits) that the demo estimate template prices from.
// The data lives in src/lib/estimator/demoProducts.ts, which the template generator reads
// too, so the SQL and the demo estimate's figures cannot disagree.
//
//   npx jiti scripts/gen-estimator-products-demo-seed.ts
//
// Re-run it (and commit the SQL) whenever demoProducts.ts changes. The SQL it writes is the
// only thing that runs in a database.

import { writeFileSync } from "node:fs";
import { join } from "node:path";
import { DEMO_BOM, DEMO_PRODUCTS, DEMO_TAX_PERCENT, demoUnitCosts } from "../src/lib/estimator/demoProducts";

const SAMPLE_ESTIMATE = "Sample villa, Riyadh (illustrative)";

const q = (v: string) => `'${v.replace(/'/g, "''")}'`;
const num = (n: number | undefined) => (n === undefined ? "null::numeric" : String(n));

const productRows = DEMO_PRODUCTS.map((p, i) =>
  `    (${i + 1}, ${q(p.sku)}, ${q(p.name)}, ${q(p.uom)}, ${q(p.item_type)}, ${q(p.description)}, ${num(p.list_price)}, ${num(p.cost)})`
).join(",\n");

const bomRows = DEMO_BOM.map((l, i) =>
  `    (${q(l.kit)}, ${q(l.component)}, ${l.qty}, ${q(l.uom)}, ${l.scrap_pct}, ${q(l.line_kind)}, ${i + 1}, ${l.note ? q(l.note) : "null::text"})`
).join(",\n");

const kitSkus = DEMO_PRODUCTS.filter((p) => p.item_type === "bom_kit").map((p) => q(p.sku)).join(", ");
const costs = demoUnitCosts();
const kitSummary = DEMO_PRODUCTS.filter((p) => p.item_type === "bom_kit").map((p) => `${p.sku} ${costs.get(p.sku)}`).join(", ");

const sql = `-- Demo catalogue for the Project Estimator, DEMO tenants only (is_demo = true).
-- Run AFTER 0133_item_types_and_bom.sql and AFTER seed-estimator-demo.sql.
-- (0133 adds item types and BOM lines; seed-estimator-demo.sql adds the template that names
-- these products. Both live under supabase/migrations/ and scripts/.)
-- Idempotent: a product whose SKU the tenant already has is skipped, a BOM line that is
-- already there is skipped, and a rerun only re-adds the rolled-up cost to the three kits.
-- GENERATED by scripts/gen-estimator-products-demo-seed.ts from
-- src/lib/estimator/demoProducts.ts; do not edit by hand, change that file and regenerate.
--
-- What it does, per demo tenant:
--   1. turns the Products module on (tenants.features.products = true);
--   2. adds ${DEMO_PRODUCTS.length} illustrative Saudi precast products in SAR with an item type and a cost price:
--      hollow-core slab and wall panels (solid, sandwich insulated) per m2, precast column and
--      beam per m3, stair flight per no., parapet per lm, grout and sealant, steel connection
--      plates, transport per trip, crane and erection crew per day (services), a mould set
--      (a tool), and the materials the kits are made of. They get the next free PRD-#### numbers;
--   3. adds the three BOM kits' components (the mould set as a USED line, which is listed
--      but not costed) and writes each kit's rolled-up cost into its cost_price, by the same
--      rule the product page's "Apply to product cost" uses: qty x (1 + scrap%) x component
--      cost, each line rounded to 2 decimals, used lines excluded (${kitSummary});
--   4. links the demo sample estimate's lines ("${SAMPLE_ESTIMATE}") to these products,
--      so the lines show the product, its reference and its kit components.
-- Everything is illustrative: placeholder costs, not a real price or any company's method.

do $seed$
declare
  t uuid;
  base int;
begin
  for t in select id from tenants where is_demo = true loop
    update tenants set features = coalesce(features, '{}'::jsonb) || '{"products": true}'::jsonb where id = t;

    select coalesce(max(nullif(regexp_replace(ref, '\\D', '', 'g'), '')::int), 0) into base
    from products where tenant_id = t and ref ~ '^PRD-\\d+$';

    with todo as (
      select v.*, row_number() over (order by v.n) as rn
      from (values
${productRows}
      ) as v(n, sku, name, uom, item_type, description, list_price, cost_price)
      where not exists (select 1 from products p where p.tenant_id = t and p.sku = v.sku)
    )
    insert into products (tenant_id, ref, name, sku, uom, item_type, description, list_price, cost_price, cost_price_as_of, tax_percent, status)
    select t, 'PRD-' || lpad((base + todo.rn)::text, 4, '0'), todo.name, todo.sku, todo.uom, todo.item_type, todo.description,
           todo.list_price, todo.cost_price, case when todo.cost_price is null then null else current_date end, ${DEMO_TAX_PERCENT}, 'active'
    from todo;

    insert into product_bom_lines (tenant_id, parent_product_id, component_product_id, qty, uom, scrap_pct, line_kind, sort_order, note)
    select t, k.id, c.id, v.qty, v.uom, v.scrap_pct, v.line_kind, v.sort_order, v.note
    from (values
${bomRows}
    ) as v(kit, component, qty, uom, scrap_pct, line_kind, sort_order, note)
    join products k on k.tenant_id = t and k.sku = v.kit
    join products c on c.tenant_id = t and c.sku = v.component
    on conflict (parent_product_id, component_product_id) do nothing;

    -- The kits' rolled-up cost, written to cost_price like "Apply to product cost".
    update products k set cost_price = r.total, cost_price_as_of = current_date, updated_at = now()
    from (
      select l.parent_product_id as pid, round(sum(round(l.qty * (1 + l.scrap_pct / 100) * c.cost_price, 2)), 2) as total
      from product_bom_lines l
      join products c on c.id = l.component_product_id and c.tenant_id = l.tenant_id
      where l.tenant_id = t and l.line_kind = 'consumed' and c.cost_price is not null
      group by l.parent_product_id
    ) r
    where k.id = r.pid and k.tenant_id = t and k.sku in (${kitSkus});

    -- Link the sample estimate's product lines to these products (and keep their reference).
    update estimate_lines el
    set product_id = p.id,
        custom_data = coalesce(el.custom_data, '{}'::jsonb) || case when p.ref is null then '{}'::jsonb else jsonb_build_object('product_ref', p.ref) end
    from estimates e, products p
    where el.tenant_id = t and e.id = el.estimate_id and e.tenant_id = t
      and e.name = ${q(SAMPLE_ESTIMATE)} and e.standard_quote_id is null
      and el.source = 'rule' and el.product_id is null
      and p.tenant_id = t and p.status = 'active' and p.sku = el.custom_data->>'sku';
  end loop;
end
$seed$;
`;

writeFileSync(join(__dirname, "seed-estimator-products-demo.sql"), sql, "utf8");
console.error(`wrote scripts/seed-estimator-products-demo.sql: ${DEMO_PRODUCTS.length} products, ${DEMO_BOM.length} BOM lines; kits ${kitSummary}`);
