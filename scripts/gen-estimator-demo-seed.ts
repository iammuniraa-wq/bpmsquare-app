// Generates scripts/seed-estimator-demo.sql from the REAL estimator engine, so the
// demo estimate's lines, totals and 3D model are what "Calculate" would produce,
// not hand-typed numbers.
//
//   npx jiti scripts/gen-estimator-demo-seed.ts
//
// Re-run it (and commit the SQL) whenever the starter template or the engine's
// output changes. The SQL it writes is the only thing that runs in a database.

import { writeFileSync } from "node:fs";
import { join } from "node:path";
import { PRECAST_VILLA_STARTER } from "../src/lib/estimator/starterTemplates";
import { validateTemplate } from "../src/lib/estimator/template";
import { computeEstimate } from "../src/lib/estimator/compute";
import { persistLine } from "../src/lib/estimator/lines";

const MARGIN_PCT = 18;
const VAT_PCT = 15;
const ESTIMATE_NAME = "Sample villa, Riyadh (illustrative)";

const s = PRECAST_VILLA_STARTER;
const valid = validateTemplate({ geometry: s.geometry, inputs: s.inputs, rates: s.rates, rules: s.rules });
if (!valid.ok || !valid.template) throw new Error(`The starter does not validate: ${JSON.stringify(valid.issues)}`);

const r = computeEstimate(valid.template, {}, { margin_pct: MARGIN_PCT, vat_pct: VAT_PCT });
if (!r.ok) throw new Error(`The starter does not compute: ${JSON.stringify(r.issues)}`);
if (!r.complete) throw new Error("The starter has unpriced product lines; the demo estimate would not be quotable.");

const lines = r.lines.map((l) => persistLine(l, null, null));
const totals = { ...r.summary, unpriced: [], unresolved: [], pricing: {}, warnings: r.warnings };

// Dollar-quote tags that cannot occur in the JSON (a quote tag would end the literal early).
function dq(tag: string, value: unknown): string {
  const json = JSON.stringify(value);
  if (json.includes(`$${tag}$`)) throw new Error(`The JSON contains the quote tag $${tag}$`);
  return `$${tag}$${json}$${tag}$::jsonb`;
}

const sql = `-- Demo data for the Project Estimator, DEMO tenants only (is_demo = true).
-- Run AFTER supabase/migrations/0131_estimator.sql. Idempotent.
-- GENERATED by scripts/gen-estimator-demo-seed.ts from the real engine; do not
-- edit by hand, change the starter template or the engine and regenerate.
--
-- What it does, per demo tenant:
--   1. turns the estimator module on (tenants.features.estimator = true);
--   2. adds the template "${s.name}" if the tenant has none by that name;
--   3. adds ONE sample estimate "${ESTIMATE_NAME}" if it is not there yet, with
--      its computed lines, totals and 3D piece model already stored, so the
--      page shows everything without pressing Calculate. Margin ${MARGIN_PCT}%, VAT ${VAT_PCT}%.
-- Everything is illustrative: placeholder rates and rules, not a real price.

do $seed$
declare
  t uuid;
  tpl uuid;
  tpl_version int;
  acct uuid;
  cur text;
  est uuid;
  next_seq int;
begin
  for t in select id from tenants where is_demo = true loop
    update tenants set features = coalesce(features, '{}'::jsonb) || '{"estimator": true}'::jsonb where id = t;

    if not exists (select 1 from estimate_templates where tenant_id = t and lower(name) = lower(${sqlText(s.name)})) then
      insert into estimate_templates (tenant_id, name, description, trade, geometry, version, is_active, quote_granularity, inputs, rates, rules)
      values (
        t, ${sqlText(s.name)}, ${sqlText(s.description)}, ${sqlText(s.trade)}, ${sqlText(s.geometry ?? "")}, 1, true, ${sqlText(s.quote_granularity)},
        ${dq("inputs", valid.template.inputs)},
        ${dq("rates", valid.template.rates)},
        ${dq("rules", valid.template.rules)}
      );
    end if;

    select id, version into tpl, tpl_version from estimate_templates where tenant_id = t and lower(name) = lower(${sqlText(s.name)});

    if tpl is not null and not exists (select 1 from estimates where tenant_id = t and name = ${sqlText(ESTIMATE_NAME)}) then
      select id into acct from accounts where tenant_id = t order by name limit 1;
      select nullif(config->>'currency', '') into cur from tenants where id = t;

      select coalesce(max(nullif(regexp_replace(ref, '\\D', '', 'g'), '')::int), 0) + 1 into next_seq
      from estimates where tenant_id = t and ref ~ '^EST-\\d+$';

      insert into estimates (tenant_id, ref, name, account_id, template_id, template_version, status, params, currency, margin_pct, totals, model, notes)
      values (
        t, 'EST-' || lpad(next_seq::text, 4, '0'), ${sqlText(ESTIMATE_NAME)}, acct, tpl, tpl_version, 'draft',
        ${dq("params", r.params)}, cur, ${MARGIN_PCT},
        ${dq("totals", totals)} || jsonb_build_object('computed_at', now()),
        ${dq("model", r.model)},
        'Illustrative sample for demonstrations: placeholder rates, not a real price.'
      ) returning id into est;

      insert into estimate_lines (tenant_id, estimate_id, sort_order, code, group_key, description, uom, qty, waste_pct, unit_cost, cost_total, component, source, element_ref, wbs_code, custom_data)
      select t, est, (l->>'sort_order')::int, l->>'code', l->>'group_key', l->>'description', l->>'uom',
             (l->>'qty')::numeric, coalesce((l->>'waste_pct')::numeric, 0), (l->>'unit_cost')::numeric, (l->>'cost_total')::numeric,
             l->>'component', coalesce(l->>'source', 'rule'), l->>'element_ref', l->>'wbs_code', l->'custom_data'
      from jsonb_array_elements(${dq("lines", lines)}) as l;
    end if;
  end loop;
end
$seed$;
`;

function sqlText(v: string): string {
  return `'${v.replace(/'/g, "''")}'`;
}

writeFileSync(join(__dirname, "seed-estimator-demo.sql"), sql, "utf8");
console.error(`wrote scripts/seed-estimator-demo.sql: ${lines.length} lines, ${r.model?.pieces.length ?? 0} pieces, cost ${r.summary.cost_total}, total incl. VAT ${r.summary.price_incl_vat}`);
